import * as clc from "colorette";
import { randomUUID } from "node:crypto";

import { Command } from "../command";
import { needProjectNumber } from "../projectUtils";
import { listDebugTokens } from "../appcheck/api";
import {
  ensureCanCreateOrOverwriteDebugToken,
  getDebugTokenValidationError,
  getDefaultDisplayName,
  getDisplayNameValidationError,
  isWebAppId,
  provisionDebugToken,
  validateDebugTokenUuid,
  validateDisplayName,
} from "../appcheck/debugTokens";
import { getLocalConfigPath } from "../appcheck/localConfig";
import { DebugToken, AppCheckDebugOptions } from "../appcheck/types";
import { getOrPromptProjectAndAppId } from "./appcheck-prompts";
import { requireAuth } from "../requireAuth";
import { promiseWithSpinner, logSuccess } from "../utils";
import { FirebaseError } from "../error";
import { confirm, input, password, select } from "../prompt";
import { logger } from "../logger";

export const command = new Command("appcheck:debugtokens:create [debugToken]")
  .description("generate and register an App Check debug token for an app")
  .help(
    `generates or registers a Firebase App Check debug token for an app and saves it to the local machine configuration (~/.config/configstore/firebase-appcheck.json) so local SDKs can discover it automatically.

Pass an optional \`[debugToken]\` UUID v4 to register a specific token, or omit it to generate a new UUID v4 token. Use \`--no-save-local\` when provisioning tokens for remote CI environments to avoid modifying the local config file.`,
  )
  .option("--app <appId>", "the app id of your Firebase app")
  .option("--display-name <displayName>", "display name for the debug token (max 50 characters)")
  .option("--no-save-local", "do not save the debug token to the local machine config")
  .withForce(
    "accept default prompts and overwrite any existing debug token with the same display name",
  )
  .before((options: AppCheckDebugOptions) => requireAuth(options))
  .action(
    async (debugToken: string | undefined, options: AppCheckDebugOptions): Promise<string> => {
      const validatedTokenArg =
        debugToken !== undefined ? validateDebugTokenUuid(debugToken) : undefined;
      const validatedDisplayNameOpt =
        options.displayName !== undefined ? validateDisplayName(options.displayName) : undefined;
      const saveLocal = options.saveLocal !== false;

      const { appId } = await getOrPromptProjectAndAppId(options);
      const projectNumber = await needProjectNumber(options);

      let token = validatedTokenArg;
      if (!token) {
        if (!options.nonInteractive && !options.force) {
          const action = await select({
            message:
              "Would you like to register a token generated by the SDK, or create a new one?",
            choices: [
              { name: "Create a new debug token", value: "generate" },
              { name: "Register a token generated by the SDK", value: "sdk" },
            ],
          });
          if (action === "sdk") {
            const entered = await password({
              message: "Enter the debug token generated by the SDK:",
              validate: (val) => getDebugTokenValidationError(val) ?? true,
            });
            token = validateDebugTokenUuid(entered);
          } else {
            token = randomUUID();
          }
        } else {
          token = randomUUID();
        }
      }

      let displayName = validatedDisplayNameOpt;
      if (!displayName) {
        const defaultName = getDefaultDisplayName(saveLocal);
        if (!options.nonInteractive && !options.force) {
          const entered = await input({
            message: "What would you like to call this debug token?",
            default: defaultName,
            validate: (val) => getDisplayNameValidationError(val) ?? true,
          });
          displayName = validateDisplayName(entered);
        } else {
          displayName = defaultName;
        }
      }

      const existingTokens = await listDebugTokens(projectNumber, appId);
      const matchingTokens = existingTokens.filter((t) => t.displayName === displayName);
      ensureCanCreateOrOverwriteDebugToken({ appId, existingTokens, matchingTokens });

      if (matchingTokens.length > 0 && !options.force) {
        if (options.nonInteractive) {
          throw new FirebaseError(
            `A token with the display name "${displayName}" already exists. Must pass --force to overwrite in non-interactive mode.`,
            { exit: 1 },
          );
        }
        const shouldOverwrite = await confirm({
          message: `A token with the display name "${displayName}" already exists. Replace the existing token(s)?`,
          default: true,
        });
        if (!shouldOverwrite) {
          throw new FirebaseError("Registration canceled.", { exit: 1 });
        }
      }

      const result = await promiseWithSpinner<DebugToken>(
        () =>
          provisionDebugToken({
            projectNumber,
            appId,
            displayName,
            token,
            existingTokens,
            matchingTokens,
            saveLocal,
          }),
        `Registering App Check debug token with Firebase for app ${clc.bold(appId)}`,
      );

      const finalToken = result.token || token;
      logSuccess(`Successfully registered App Check debug token:
  - Display Name: ${clc.bold(result.displayName)}
  - Resource Name: ${clc.cyan(result.name)}
  - Token: ${clc.bold(clc.green(finalToken))}`);

      if (saveLocal) {
        logger.info(`Saved debug token to local config: ${clc.bold(getLocalConfigPath())}`);
      }

      if (isWebAppId(appId)) {
        logger.info(
          `\nWeb Framework Instructions:\n` +
            `Copy and paste the relevant variable into your local environment file (${clc.bold(".env.local")}), or export the debug token as a shell environment variable:\n` +
            `  # Vite\n` +
            `  VITE_FIREBASE_APPCHECK_DEBUG_TOKEN=${finalToken}\n` +
            `  # Next.js\n` +
            `  NEXT_PUBLIC_FIREBASE_APPCHECK_DEBUG_TOKEN=${finalToken}\n` +
            `  # Create React App\n` +
            `  REACT_APP_FIREBASE_APPCHECK_DEBUG_TOKEN=${finalToken}\n` +
            `Assign this variable to ${clc.bold("self.FIREBASE_APPCHECK_DEBUG_TOKEN")} in your app initialization code before initializing App Check.\n` +
            `Ensure ${clc.bold(".env.local")} is in your ${clc.bold(".gitignore")} so debug tokens are never committed.`,
        );
      }

      logger.info(
        clc.yellow(
          clc.bold("Warning: ") +
            "App Check debug tokens grant access to backend resources and are secrets. Do NOT commit debug tokens or .env.local to source repositories. Revoke unused tokens with 'firebase appcheck:debugtokens:delete'.",
        ),
      );

      return finalToken;
    },
  );
